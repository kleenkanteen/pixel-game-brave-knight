// Pre-compile each glyph into horizontal ink runs: [x, y, w] — fewer fillRects.
const GLYPHS = {};
for (const [ch, rows] of Object.entries(G)) {
  const runs = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        const start = x;
        while (row[x] === '#') x++;
        runs.push([start, y, x - start]);
      } else x++;
    }
  });
  GLYPHS[ch] = { w: rows[0].length, runs };
}

const glyphWidth = (ch) => (ch === ' ' ? SPACE_W : (GLYPHS[ch]?.w ?? SPACE_W));

/** True when the font has a glyph for `ch` (space counts). */
export const hasGlyph = (ch) => ch === ' ' || ch in GLYPHS;

/**
 * Width in px of `str` at scale 1 (no trailing letter gap).
 * @param {string} str
 * @param {number} [scale=1]
 */
export function measureText(str, scale = 1) {
  if (!str) return 0;
  let w = 0;
  for (const ch of str) w += glyphWidth(ch) + LETTER_GAP;
  return (w - LETTER_GAP) * scale;
}

function drawRuns(ctx, str, x, y, scale) {
  let cx = x;
  for (const ch of str) {
    const g = GLYPHS[ch];
    if (g) for (const [rx, ry, rw] of g.runs) ctx.fillRect(cx + rx * scale, y + ry * scale, rw * scale, scale);
    cx += (glyphWidth(ch) + LETTER_GAP) * scale;
  }
}

/**
 * Draw pixel text. `y` is the TOP of the 7px cell (descenders hang 2px below).
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} str
 * @param {number} x   left edge, or centre when align = 'center', right edge for 'right'
 * @param {number} y
 * @param {{color?:string, align?:'left'|'center'|'right', shadow?:boolean|string,
 *          outline?:boolean|string, scale?:number}} [opts]
 *   shadow: 1px drop shadow down-right (true = dark default or a colour)
 *   outline: 1px outline all round (true = dark default or a colour)
 */
export function drawText(ctx, str, x, y, opts = {}) {
  const { color = '#ffffff', align = 'left', shadow = false, outline = false, scale = 1 } = opts;
  const w = measureText(str, scale);
  let left = x;
  if (align === 'center') left = x - Math.floor(w / 2);
  else if (align === 'right') left = x - w;
  left = Math.round(left);
  y = Math.round(y);

  if (outline) {
    ctx.fillStyle = outline === true ? '#14101c' : outline;
    for (let oy = -1; oy <= 1; oy++)
      for (let ox = -1; ox <= 1; ox++) if (ox || oy) drawRuns(ctx, str, left + ox * scale, y + oy * scale, scale);
  } else if (shadow) {
    ctx.fillStyle = shadow === true ? '#14101c' : shadow;
    drawRuns(ctx, str, left + scale, y + scale, scale);
  }
  ctx.fillStyle = color;
  drawRuns(ctx, str, left, y, scale);
  return w;
}
